// Regenerates lib/notes/wol-catalog.ts from the public WOL "todas as publicações"
// index. Run: node scripts/gen-wol-catalog.mjs
import fs from "node:fs";

const BASE = "https://wol.jw.org";
const CATEGORIES = ["livros", "brochuras-e-livretos", "folhetos", "séries-de-artigos", "apostilas"];
const decode = (s) =>
  s.replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16))).replace(/&amp;/g, "&").replace(/&quot;/g, '"').replace(/&nbsp;/g, " ");

const out = new Map();
for (const category of CATEGORIES) {
  const url = `${BASE}/pt/wol/library/r5/lp-t/todas-as-publicações/${encodeURI(category)}`;
  const html = await (await fetch(url, { headers: { "User-Agent": "Mozilla/5.0" } })).text();
  for (const m of html.matchAll(/<a href="\/pt\/wol\/publication\/r5\/lp-t\/([^"]+)"[^>]*>([\s\S]*?)<\/a>/g)) {
    const slug = decodeURIComponent(m[1]).toLowerCase();
    if (slug.includes("/")) continue;
    const text = decode(m[2].replace(/<[^>]+>/g, " ")).replace(/\s+/g, " ").trim();
    const t = /^(.*?)\s*\(([^)]+)\)\s*(\d{4})?$/.exec(text);
    const title = (t?.[1] ?? text).trim();
    if (!title) continue;
    if (!out.has(slug)) out.set(slug, { symbol: slug, title, category });
  }
}
const rows = [...out.values()].sort((a, b) => a.symbol.localeCompare(b.symbol));
const body = rows.map((r) => `  [${JSON.stringify(r.symbol)}, ${JSON.stringify(r.title)}],`).join("\n");
fs.writeFileSync(
  new URL("../lib/notes/wol-catalog.ts", import.meta.url),
  `// GENERATED by scripts/gen-wol-catalog.mjs — non-periodical publications in the WOL index (symbol, title).\n// Used only to turn a name ("Achegue-se a Jeová 10") into the symbol WOL understands ("cl 10").\nexport const WOL_CATALOG: ReadonlyArray<readonly [symbol: string, title: string]> = [\n${body}\n];\n`
);
console.log(rows.length, "publications");
